/**
 * Light, air and water.
 *
 * Everything here is a real object in the world with a real position. That is a
 * rule rather than a preference: the alternative implementation of most of it is
 * a screen-space effect, and screen-space is exactly what makes a trip read as a
 * filter. Sun shafts are geometry. Fog is fog. Motes are points at coordinates.
 * Turn your head and all of it stays where it was.
 *
 * …and since the clock arrived, all of it also has an HOUR. `daylight.js` owns
 * what time it is and defends the twenty-minute cycle; this file owns what that
 * hour looks like. The division is worth stating because it is the reason the
 * two can be tested apart: `daylight.js` is pure arithmetic with no scene in it
 * and can be run in node, and everything below is application with no opinions
 * about time in it at all.
 */

/**
 * Direction the sun comes from AT NINE IN THE MORNING.
 *
 * Mid-morning rather than golden hour. A low sun gives long dramatic shadows in
 * an open field and, in a forest, gives a hundred metres of horizontal stripes
 * across the ground that read as corduroy. Raising it to about 35° puts the
 * light through the canopy instead of along it, which is the dappled floor a
 * wood is supposed to have.
 *
 * THAT PARAGRAPH SURVIVED THE DAY CYCLE INTACT, AND IT IS WHY THE LIGHT HAS A
 * FLOOR ON ITS ELEVATION.
 *
 * The obvious way to build a day is to swing the sun from horizon to horizon,
 * and it walks straight into the corduroy this constant was chosen to avoid —
 * twice a cycle, for a couple of minutes each time, at exactly the moment the
 * player is most likely to stop and look at the sky. So the DIRECT light stops
 * descending at 30° and fades out there instead (see SUN_FLOOR in daylight.js),
 * the dawn and dusk fog closes the wood in to about sixty metres so there is no
 * hundred metres of anything to stripe, and the SKY's sun disc goes on down to
 * the true horizon so you can still watch it set. What reads as evening is the
 * colour, the fog and the azimuth swinging round — not the elevation, which in a
 * wood is mostly hidden by the canopy anyway.
 *
 * This vector is still the anchor of the whole model rather than one sample of
 * it: the day arc is generated by rotating THIS about the celestial pole, so at
 * `AUTHORED_PHASE` the rotation is the identity and the sun is here, bit for
 * bit. Everything the fifteen scripts in scripts/ measured before there was a
 * clock, they still measure — see the automation pin in daylight.js.
 */
export const SUN_DIR = new THREE.Vector3(0.36, 0.62, -0.7).normalize();

/**
 * Metres the body may stray from the sun's anchor before the anchor follows.
 *
 * This is the whole frequency control on the most expensive event in the app —
 * see `follow()` for what one costs and why hysteresis rather than a lattice.
 * The value is not free to choose: the anchor may now trail the body by the
 * full radius, and forest.js keeps every tree within `alwaysNear: 82` m in the
 * instance buffer on the arithmetic 58 (shadow half-extent) + ~6 (trail) + ~15
 * (a leaning canopy reaching past its trunk). Raising this without raising
 * that would let a tree be culled from the buffer while its shadow was still
 * inside the shadow camera, and its shadow would blink off the ground in front
 * of you. They move together or not at all.
 */
const ANCHOR_HOLD = 6;

/**
 * ---------------------------------------------------------------------------
 * HOW A MOVING SUN IS AFFORDED AT ALL
 * ---------------------------------------------------------------------------
 *
 * This is the hardest constraint in the day cycle and it deserves the space.
 *
 * A shadow map re-render costs 3.2–4.5 ms on top of a 2.2–2.8 ms frame — see
 * the block in `follow` and the one in main.js. Everything about the anchor is
 * arranged so that standing still costs ZERO of them, and a sun that moves
 * invalidates the map continuously, which naively means paying that price every
 * frame for ever. That is not a 12% regression, it is roughly tripling the
 * frame cost of the whole game.
 *
 * FOUR THINGS TOGETHER MAKE IT FREE ENOUGH.
 *
 * 1. THE LIGHT IS QUANTISED, NOT THE MAP. The obvious move is to let the
 *    DirectionalLight rotate smoothly and re-render the shadow map only every
 *    so often. It is wrong, and badly: the diffuse term would then rotate a
 *    degree at a time while the shadows stood still, so the lit and the
 *    shadowed parts of the frame would visibly disagree about where the sun is,
 *    and shadows would appear to lag the light. Quantising THE LIGHT ITSELF
 *    keeps them consistent by construction — the whole lighting solution steps,
 *    and the shadow map is simply re-rendered on the step. A Lambert term moves
 *    by sin(step) when the light does, which at a degree is a 1.7% change on a
 *    surface: an order of magnitude below anything you can see, and two below
 *    the shadow displacement it buys.
 *
 *    The SKY does not step. Its sun disc, its glow and the water's specular
 *    take the true continuous direction, because those are the three places
 *    where a degree is a whole feature wide.
 *
 * 2. THE STEP IS SIZED BY WHAT IT DISPLACES. A shadow cast from h metres up
 *    moves h·Δθ when the light turns Δθ, so 1.2° under a 12 m canopy is 25 cm —
 *    four texels of the 2048² map over its 116 m extent, and inside the PCF
 *    kernel's own softness. Measured as a mean absolute pixel difference over
 *    the six standard stations, a 1.2° step is 0.31/255 and a 2.4° step is
 *    0.62/255; the eye's threshold on a smooth gradient is around 1/255 and on
 *    a dappled forest floor is far higher. See scripts/day-check.mjs, which
 *    prints that table.
 *
 * 3. THE STEP WIDENS AS THE LIGHT WEAKENS. What is actually visible is the
 *    displacement TIMES the contrast, and the contrast is the directional's
 *    intensity. So the threshold is divided by it: at full noon sun the step is
 *    SUN_STEP, and by the time the light is the moon at 0.18 it is five times
 *    coarser and costs almost nothing. This is most of the saving over a whole
 *    cycle, because most of a cycle is not noon.
 *
 * 4. MOVING IS FREE. `follow` already re-renders the map when the player walks
 *    six metres, so on that frame the sun's pending step is committed as well
 *    and costs nothing at all. A walking player therefore pays exactly what
 *    they paid before this feature existed; only a stationary one pays anything
 *    — and a stationary player pays about a tenth of what walking costs.
 *
 * WHAT IT MEASURES AT. Standing still, over a whole cycle, this comes out at
 * about 9 re-renders a minute — against the ~40 a minute that walking at 4 m/s
 * has always produced. That is the number that makes the feature affordable:
 * the clock can never be the thing you notice, because ordinary movement is
 * already four times louder.
 */
const SUN_STEP = 1.2 * (Math.PI / 180);
/**
 * The coarsest the step is allowed to get. Without a ceiling the moon at the
 * handover, where the intensity passes through zero, would ask for an infinite
 * step and the light would stop tracking altogether — and then the first frame
 * the intensity came back up would swing it a long way at once.
 */
const SUN_STEP_MAX = 10 * (Math.PI / 180);
/**
 * The elevation the shadow bias was authored at, so the bias can be widened as
 * the sun drops and narrowed back to exactly 0.05 when it returns. Depth-buffer
 * acne is a function of the angle between the light and the surface, and a 30°
 * sun on a 25° slope is very nearly the worst case a forest floor offers.
 */
const AUTHORED_SIN_ELEVATION = SUN_DIR.y;

